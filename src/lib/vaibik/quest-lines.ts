/**
 * Билдеры динамических реплик (со вставкой выбранной темы/действия).
 * Каждая функция возвращает финальный текст реплики и имеет тот же
 * «смысловой ключ», что и статические реплики, для будущего аудио.
 */

/** Лаборатория: вопрос про действие после выбора темы. Ключ: `lab.action.prompt`. */
export function labActionPrompt(themeLabel: string): string {
  return `Отлично — ${themeLabel.toLowerCase()}! А что будем делать? Выбери действие:`;
}

/** Лаборатория: финальная реплика перед сборкой игры. Ключ: `lab.done`. */
export function labDone(themeLabel: string, actionLabel: string): string {
  return `Отлично! ${themeLabel} + ${actionLabel.toLowerCase()} — теперь я всё понял и построю твою игру!`;
}

/** Итерация: приглашение собрать предметы. Ключ: `iteration.play`. */
export function iterationPlay(collectible: string): string {
  return `Проверь игру, что я построил! Собери все светящиеся ${collectible}!`;
}

/** Программа VibeCraft: реплика после ввода темы. Ключ: `program.theme`. */
export function programTheme(themePromptWord: string): string {
  return `Смотри! Я написал тему — «игра про ${themePromptWord}». И справа уже появляется то, о чём эта игра!`;
}

/** Программа VibeCraft: реплика после ввода действия. Ключ: `program.action`. */
export function programAction(actionPrompt: string): string {
  return `Теперь допишу действие: «${actionPrompt}». Смотри, справа появилась цель игры!`;
}

/**
 * Получить текст статической реплики по id-ключу.
 * Если ключ неизвестен — возвращает пустую строку (без ошибок).
 */
export function getLine(id: string): string {
  return LINE_TEXT[id] ?? "";
}
