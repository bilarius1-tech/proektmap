export const NAV_ICON_NAMES = Object.keys(NAV_ICONS).sort();

export function hasNavIcon(name?: string | null) {
  return Boolean(name && NAV_ICONS[name]);
}

export default function NavIcon({ name, size = 16 }: { name?: string | null; size?: number }) {
  const Icon = (name && NAV_ICONS[name]) || Circle;
  return <Icon size={size} strokeWidth={2} aria-hidden />;
}
